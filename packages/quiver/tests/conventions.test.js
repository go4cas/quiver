// @vitest-environment node
// TECH-SPEC §12.3, S-50…S-59: scanApp, generateApp and isAppFile.
import { describe, it, expect } from 'vitest'
import { cpSync, mkdirSync, mkdtempSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { generateApp, isAppFile, scanApp } from '../src/node/conventions.js'

const FIXTURES = join(import.meta.dirname, 'fixtures')

/** @param {Record<string, string>} files path → content, under a fresh source dir */
function app(files) {
  const src = mkdtempSync(join(tmpdir(), 'quiver-app-'))
  for (const [path, content] of Object.entries(files)) {
    mkdirSync(join(src, path, '..'), { recursive: true })
    writeFileSync(join(src, path), content)
  }
  return src
}

const PAGE = "export default () => ''\n"

describe('scanApp', () => {
  it('S-50…S-55: reads every convention folder of the fixture', async () => {
    const scan = await scanApp(join(FIXTURES, 'app'))
    expect(scan.layouts).toEqual([{ name: 'default', file: 'layouts/default.js' }, { name: 'menu', file: 'layouts/menu.js' }])
    expect(scan.middleware).toEqual(['middleware/01.auth.js', 'middleware/02.analytics.js'])
    expect(scan.sections).toEqual([
      { pattern: '/admin', file: 'pages/admin/_middleware.js' },
      { pattern: '/admin/:id', file: 'pages/admin/[id]/_middleware.js' },
    ])
    expect(scan.views).toEqual({ loading: 'views/loading.js', error: 'views/error.js' })
    expect(scan.config).toBe('app.config.js')
    expect(scan.notFound).toBe('pages/not-found.js')
    expect(scan.routes.map((r) => r.file)).not.toContain('pages/admin/_middleware.js')
  })

  it('S-57: nav sorts by order, unnumbered last, then by path', async () => {
    const src = app({
      'pages/index.js': "export const meta = { nav: { label: 'Home', order: 1 } }\n" + PAGE,
      'pages/b.js': "export const meta = { nav: { label: 'B' } }\n" + PAGE,
      'pages/a.js': "export const meta = { nav: { label: 'A' } }\n" + PAGE,
      'pages/z.js': "export const meta = { nav: { label: 'Z', order: 0 } }\n" + PAGE,
    })
    expect((await scanApp(src)).nav).toEqual([
      { to: '/z', label: 'Z' }, { to: '/', label: 'Home' }, { to: '/a', label: 'A' }, { to: '/b', label: 'B' },
    ])
  })

  it('a pages-only app: empty parts, no warnings, and no layout check without layouts/', async () => {
    const src = app({ 'pages/index.js': "export const meta = { layout: 'anything' }\n" + PAGE })
    const scan = await scanApp(src)
    expect(scan).toEqual({
      routes: [{ pattern: '/', file: 'pages/index.js' }], notFound: null, layouts: [], middleware: [], sections: [],
      views: { loading: null, error: null }, config: null, nav: [], warnings: [],
    })
    expect(generateApp(scan, (f) => `./${f}`)).toBe([
      '// Generated by Quiver. Do not edit.',
      'export default {',
      '  routes: {',
      "    '/': () => import('./pages/index.js'),",
      '  },',
      '  notFound: undefined,',
      '  layouts: {},',
      '  middleware: { global: [], sections: {} },',
      '  views: {},',
      '  nav: [],',
      '  config: {},',
      '}',
      '',
    ].join('\n'))
  })

  it('S-53: a root _middleware.js is the "/" section; one in a skipped folder is not read', async () => {
    const src = app({ 'pages/index.js': PAGE, 'pages/_middleware.js': PAGE, 'pages/_parts/_middleware.js': PAGE, 'pages/.x/_middleware.js': PAGE })
    expect((await scanApp(src)).sections).toEqual([{ pattern: '/', file: 'pages/_middleware.js' }])
  })

  it('S-50: a pages directory outside srcDir gives ../ files', async () => {
    const root = mkdtempSync(join(tmpdir(), 'quiver-app-'))
    cpSync(join(FIXTURES, 'pages'), join(root, 'routes'), { recursive: true })
    mkdirSync(join(root, 'src'))
    const scan = await scanApp(join(root, 'src'), { pagesDir: join(root, 'routes') })
    expect(scan.routes[0]).toEqual({ pattern: '/', file: '../routes/index.js' })
  })

  it('S-50: page errors and convention errors are reported together, once', async () => {
    const src = app({ 'pages/a.js': PAGE, 'pages/a/index.js': PAGE, 'views/header.js': PAGE })
    await expect(scanApp(src)).rejects.toThrow(
      '[quiver] a.js and a/index.js both map to "/a".\n[quiver] views/header.js: only loading.js and error.js are read from views/.',
    )
  })

  it('S-51: non-.js files and _ helpers in layouts/ are ignored', async () => {
    const src = app({ 'pages/index.js': PAGE, 'layouts/menu.js': PAGE, 'layouts/menu.css': '', 'layouts/_util.js': PAGE })
    expect((await scanApp(src)).layouts).toEqual([{ name: 'menu', file: 'layouts/menu.js' }])
  })
})

describe('isAppFile (S-61)', () => {
  const src = '/app/src'
  const pages = '/app/src/pages'
  it.each([
    ['/app/src/pages/about.js', true],
    ['/app/src/pages/admin/_middleware.js', true],
    ['/app/src/pages/_parts/Card.js', false],
    ['/app/src/pages/_parts/_middleware.js', false],
    ['/app/src/pages/notes.md', false],
    ['/app/src/layouts/menu.js', true],
    ['/app/src/layouts/menu.css', false],
    ['/app/src/layouts/_parts/x.js', false],
    ['/app/src/middleware/01.auth.js', true],
    ['/app/src/views/error.js', true],
    ['/app/src/app.config.js', true],
    ['/app/src/main.js', false],
    ['/app/src/components/Card.js', false],
  ])('%s → %s', (file, expected) => {
    expect(isAppFile(src, pages, file)).toBe(expected)
  })
})
