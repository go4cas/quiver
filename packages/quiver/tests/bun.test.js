// @vitest-environment node
// TECH-SPEC §4.4, S-20…S-22: the Bun plugin.
import { describe, it, expect, vi } from 'vitest'
import { spawnSync } from 'node:child_process'
import { mkdtempSync, readdirSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import quiver from '../src/node/bun.js'
import { fakeBunBuild } from './helpers/frontends.js'

const FIXTURES = join(import.meta.dirname, 'fixtures')
const hasBun = spawnSync('bun', ['--version']).status === 0

describe('Bun plugin', () => {
  it('S-20: resolves quiver:routes into the quiver namespace and loads it as js', async () => {
    const { build, resolvers, loaders } = fakeBunBuild()
    const plugin = quiver({ dir: join(FIXTURES, 'pages') })
    expect(plugin.name).toBe('quiver:routes')
    plugin.setup(build)

    expect(resolvers).toHaveLength(1)
    expect(resolvers[0].options.filter.test('quiver:routes')).toBe(true)
    expect(resolvers[0].options.filter.test('quiver:routes2')).toBe(false)
    expect(resolvers[0].callback({ path: 'quiver:routes' })).toEqual({ path: 'quiver:routes', namespace: 'quiver' })

    expect(loaders).toHaveLength(1)
    expect(loaders[0].options.namespace).toBe('quiver')
    const result = await loaders[0].callback({ path: 'quiver:routes', namespace: 'quiver' })
    expect(result.loader).toBe('js')
    expect(result.contents).toMatch(/^\/\/ Generated by Quiver\. Do not edit\.\n/)
  })

  it('S-62: resolves quiver:app into the same namespace and loads the app manifest; warnings go to console.warn', async () => {
    const { build, resolvers, loaders } = fakeBunBuild()
    quiver({ srcDir: join(FIXTURES, 'app') }).setup(build)
    expect(resolvers[0].options.filter.test('quiver:app')).toBe(true)
    expect(resolvers[0].options.filter.test('quiver:apps')).toBe(false)
    expect(resolvers[0].callback({ path: 'quiver:app' })).toEqual({ path: 'quiver:app', namespace: 'quiver' })
    const warn = vi.spyOn(console, 'warn').mockImplementation(() => {})
    try {
      const result = await loaders[0].callback({ path: 'quiver:app', namespace: 'quiver' })
      expect(result.loader).toBe('js')
      expect(result.contents).toContain("  layouts: { 'default': layout0, 'menu': layout1 },")
      expect(warn).toHaveBeenCalledWith('[quiver] typo.js: unknown layout "menuu" (layouts: default, menu).')
      const routes = await loaders[0].callback({ path: 'quiver:routes', namespace: 'quiver' })
      expect(routes.contents).toContain(`'/about': () => import('${join(FIXTURES, 'app', 'pages', 'about.js').replace(/\\/g, '/')}'),`)
    } finally {
      warn.mockRestore()
    }
  })

  it('dir defaults to src/pages under process.cwd()', async () => {
    const { build, loaders } = fakeBunBuild()
    quiver().setup(build)
    await expect(loaders[0].callback({ path: 'quiver:routes' })).rejects.toThrow(
      `Pages directory not found: ${join(process.cwd(), 'src', 'pages')}`,
    )
  })

  // S-21: a real Bun.build with splitting emits one chunk per page and every
  // loader imports its page from the output.
  it.skipIf(!hasBun)('S-21: Bun.build({ splitting: true }) emits one chunk per page', () => {
    const outdir = mkdtempSync(join(tmpdir(), 'quiver-bun-'))
    const { status, stdout, stderr } = spawnSync('bun', [join(FIXTURES, 'bun-build.js'), join(FIXTURES, 'pages'), outdir], { encoding: 'utf8' })
    expect(stderr).toBe('')
    expect(status).toBe(0)
    const report = JSON.parse(stdout)
    expect(report.kinds).toEqual([...Array(8).fill('chunk'), 'entry-point'])
    expect(report.pages).toEqual({
      '/': 'home', '/about': 'about', '/blog/:slug/comments': 'comments', '/café': 'café', '/release notes': 'release notes', '/users': 'users', '/users/:id': 'user',
    })
    expect(report.notFound).toBe('not found')
    expect(readdirSync(outdir).filter((f) => f.startsWith('chunk-'))).toHaveLength(8)
  })
})
